const char kComp[] = "xyzw";

template <typename... A>
std::string fmt(const char* f, A... a) {
    char buf[512];
    std::snprintf(buf, sizeof buf, f, a...);
    return buf;
}

std::string swizzle(const u8 s[4]) {
    if (s[0] == 0 && s[1] == 1 && s[2] == 2 && s[3] == 3) return "";
    std::string r = ".";
    for (int c = 0; c < 4; ++c) r += kComp[s[c]];
    return r;
}

// Write mask as a component string. `bits` has x in bit `xbit` and the
// other components following in the given direction.
std::string mask_vp(u32 m) {  // VP: bit 3 = x .. bit 0 = w
    std::string r;
    if (m & 8) r += 'x';
    if (m & 4) r += 'y';
    if (m & 2) r += 'z';
    if (m & 1) r += 'w';
    return r;
}
std::string mask_fp(u32 m) {  // FP: bit 0 = x .. bit 3 = w
    std::string r;
    for (int c = 0; c < 4; ++c)
        if (m & (1u << c)) r += kComp[c];
    return r;
}

// bvec4 condition for a condition code test. Empty string = always.
// Returns "false" when the condition can never be true.
std::string cond_expr(u32 cond, const std::string& cc) {
    switch (cond & 7) {
    case 0: return "false";
    case 1: return "lessThan(" + cc + ", vec4(0.0))";
    case 2: return "equal(" + cc + ", vec4(0.0))";
    case 3: return "lessThanEqual(" + cc + ", vec4(0.0))";
    case 4: return "greaterThan(" + cc + ", vec4(0.0))";
    case 5: return "notEqual(" + cc + ", vec4(0.0))";
    case 6: return "greaterThanEqual(" + cc + ", vec4(0.0))";
    default: return "";
    }
}

struct Out {
    std::string s;
    int indent = 1;
    void line(const std::string& l) {
        s.append(static_cast<std::size_t>(indent) * 4, ' ');
        s += l;
        s += '\n';
    }
};

// Emit `dst.m = value.m`, honouring a condition (bvec4 expression or "").
void write_masked(Out& o, const std::string& dst, const std::string& m, const std::string& value,
                  const std::string& cond, bool integer = false) {
    if (m.empty()) return;
    const std::string v = integer ? "ivec4(floor(" + value + "))" : value;
    if (cond.empty()) {
        o.line(dst + "." + m + " = " + v + "." + m + ";");
    } else {
        o.line(dst + "." + m + " = mix(" + dst + "." + m + ", " + v + "." + m + ", c." + m + ");");
    }
}

std::string glsl_header() {
    return "#version 450\n"
           "// generated by openTITs from RSX microcode\n";
}

