std::string fp_input(u32 attr, const FragmentOptions& opt) {
    switch (attr) {
    case fp::IN_WPOS: return "gl_FragCoord";
    case fp::IN_COL0: return opt.two_sided_color ? "(gl_FrontFacing ? in_col0 : in_bfc0)" : "in_col0";
    case fp::IN_COL1: return opt.two_sided_color ? "(gl_FrontFacing ? in_col1 : in_bfc1)" : "in_col1";
    case fp::IN_FOGC: return "in_fog";
    case fp::IN_SSA: return "vec4(gl_FrontFacing ? 1.0 : -1.0)";
    default:
        if (attr >= fp::IN_TEX0 && attr <= fp::IN_TEX9) return "in_tex" + std::to_string(attr - fp::IN_TEX0);
        return "vec4(0.0)";
    }
}

std::string fp_src(const fp::Insn& i, int n, const FragmentOptions& opt) {
    const fp::Source s = i.src(n);
    std::string r;
    switch (s.type) {
    case fp::REG_TEMP: r = (s.half ? "h" : "r") + std::to_string(s.index); break;
    case fp::REG_INPUT: r = fp_input(s.index, opt); break;
    case fp::REG_CONST:
        r = fmt("uintBitsToFloat(uvec4(0x%08Xu, 0x%08Xu, 0x%08Xu, 0x%08Xu))", i.constant[0], i.constant[1],
                i.constant[2], i.constant[3]);
        break;
    default: r = "vec4(0.0)"; break;
    }
    r += swizzle(s.swizzle);
    if (s.abs) r = "abs(" + r + ")";
    if (s.neg) r = "-" + r;
    return r;
}

TexDim dim_of(const FragmentOptions& o, u32 t) { return o.textures[t & 15] == TexDim::None ? TexDim::D2 : o.textures[t & 15]; }

std::string tex_coord(TexDim d, const std::string& c) {
    switch (d) {
    case TexDim::D1: return "(" + c + ").x";
    case TexDim::D3: case TexDim::Cube: return "(" + c + ").xyz";
    default: return "(" + c + ").xy";
    }
}

std::string fp_value(const fp::Insn& i, const FragmentOptions& opt) {
    const std::string a = fp_src(i, 0, opt), b = fp_src(i, 1, opt), c = fp_src(i, 2, opt);
    const u32 t = i.tex_num();
    const std::string sampler = "tex" + std::to_string(t);
    const TexDim d = dim_of(opt, t);
    if (i.is_texture() && (opt.shadow_mask & (1u << t))) {
        // Depth compare against the coordinate's z (projected for TXP).
        if (i.opcode() == fp::TXP || i.opcode() == fp::TXPBEM)
            return "vec4(texture(" + sampler + ", vec3((" + a + ").xy / (" + a + ").w, (" + a + ").z / (" + a + ").w)))";
        return "vec4(texture(" + sampler + ", vec3((" + a + ").xy, (" + a + ").z)))";
    }
    if (i.is_texture() && (opt.depth_rgba_mask & (1u << t))) {
        const std::string c = i.opcode() == fp::TXP ? "(" + a + ").xy / (" + a + ").w" : "(" + a + ").xy";
        return "_depth24_rgba(texture(" + sampler + ", " + c + ").r)";
    }
    switch (i.opcode()) {
    case fp::MOV: return a;
    case fp::MUL: return "(" + a + " * " + b + ")";
    case fp::ADD: return "(" + a + " + " + b + ")";
    case fp::MAD: return "(" + a + " * " + b + " + " + c + ")";
    case fp::DP3: return "vec4(dot((" + a + ").xyz, (" + b + ").xyz))";
    case fp::DP4: return "vec4(dot(" + a + ", " + b + "))";
    case fp::DP2: return "vec4(dot((" + a + ").xy, (" + b + ").xy))";
    case fp::DP2A: return "vec4(dot((" + a + ").xy, (" + b + ").xy) + (" + c + ").z)";
    case fp::DST: return "vec4(1.0, (" + a + ").y * (" + b + ").y, (" + a + ").z, (" + b + ").w)";
    case fp::MIN: return "min(" + a + ", " + b + ")";
    case fp::MAX: return "max(" + a + ", " + b + ")";
    case fp::SLT: return "vec4(lessThan(" + a + ", " + b + "))";
    case fp::SGE: return "vec4(greaterThanEqual(" + a + ", " + b + "))";
    case fp::SLE: return "vec4(lessThanEqual(" + a + ", " + b + "))";
    case fp::SGT: return "vec4(greaterThan(" + a + ", " + b + "))";
    case fp::SNE: return "vec4(notEqual(" + a + ", " + b + "))";
    case fp::SEQ: return "vec4(equal(" + a + ", " + b + "))";
    case fp::SFL: return "vec4(0.0)";
    case fp::STR: return "vec4(1.0)";
    case fp::FRC: return "fract(" + a + ")";
    case fp::FLR: return "floor(" + a + ")";
    case fp::DDX: return "dFdx(" + a + ")";
    case fp::DDY: return "dFdy(" + a + ")";
    case fp::RCP: return "vec4(1.0 / (" + a + ").x)";
    case fp::RSQ: return "vec4(inversesqrt(max(abs((" + a + ").x), 1.0e-38)))";
    case fp::EX2: return "vec4(exp2((" + a + ").x))";
    case fp::LG2: return "vec4(log2(max(abs((" + a + ").x), 1.0e-38)))";
    case fp::LIT: return "_lit(" + a + ")";
    case fp::LRP: return "mix(" + c + ", " + b + ", " + a + ")";
    case fp::COS: return "vec4(cos((" + a + ").x))";
    case fp::SIN: return "vec4(sin((" + a + ").x))";
    case fp::POW: return "vec4(pow(max((" + a + ").x, 0.0), (" + b + ").x))";
    case fp::DIV: return "(" + a + " / (" + b + ").x)";
    case fp::DIVSQ: return "(" + a + " * inversesqrt(max(abs((" + b + ").x), 1.0e-38)))";
    case fp::NRM: return "vec4(normalize((" + a + ").xyz), 0.0)";
    case fp::REFL: return "((" + b + ") - 2.0 * dot((" + a + ").xyz, (" + b + ").xyz) * (" + a + "))";
    case fp::LIF: return "_lit(" + a + ")";
    case fp::PK2: return "vec4(uintBitsToFloat(packHalf2x16((" + a + ").xy)))";
    case fp::UP2: return "unpackHalf2x16(floatBitsToUint((" + a + ").x)).xyxy";
    case fp::PK4: return "vec4(uintBitsToFloat(packSnorm4x8(" + a + ")))";
    case fp::UP4: return "unpackSnorm4x8(floatBitsToUint((" + a + ").x))";
    case fp::PKB: case fp::PKG: return "vec4(uintBitsToFloat(packUnorm4x8(" + a + ")))";
    case fp::UPB: case fp::UPG: return "unpackUnorm4x8(floatBitsToUint((" + a + ").x))";
    case fp::PK16: return "vec4(uintBitsToFloat(packUnorm2x16((" + a + ").xy)))";
    case fp::UP16: return "unpackUnorm2x16(floatBitsToUint((" + a + ").x)).xyxy";
    case fp::TEX: case fp::TEXBEM: return "texture(" + sampler + ", " + tex_coord(d, a) + ")";
    case fp::TXP: case fp::TXPBEM: return "texture(" + sampler + ", " + tex_coord(d, a + " / (" + a + ").w") + ")";
    case fp::TXL: return "textureLod(" + sampler + ", " + tex_coord(d, a) + ", (" + b + ").x)";
    case fp::TXB: return "texture(" + sampler + ", " + tex_coord(d, a) + ", (" + b + ").x)";
    case fp::TXD: return "textureGrad(" + sampler + ", " + tex_coord(d, a) + ", " + tex_coord(d, b) + ", " + tex_coord(d, c) + ")";
    default: return "vec4(0.0)";
    }
}

std::string fp_cond(const fp::Insn& i) {
    if (i.always_executes()) return "";
    const u32 c = (i.exec_lt() ? 1u : 0u) | (i.exec_eq() ? 2u : 0u) | (i.exec_gt() ? 4u : 0u);
    const u8 sw[4] = {static_cast<u8>(i.cond_swizzle(0)), static_cast<u8>(i.cond_swizzle(1)),
                      static_cast<u8>(i.cond_swizzle(2)), static_cast<u8>(i.cond_swizzle(3))};
    return cond_expr(c, "cc" + std::to_string(i.cond_reg()) + swizzle(sw));
}

