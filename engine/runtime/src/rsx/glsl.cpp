std::string vertex(const vp::Program& p) {
    std::string h = glsl_header();
    h += "layout(std140, set = 0, binding = 0) uniform VertexConstants { vec4 vc[468]; };\n";
    h += "layout(push_constant) uniform VertexPush { mat4 scale_offset; uint branch_bits; } pc;\n";
    for (u32 k = 0; k < 16; ++k)
        if (p.inputs_read & (1u << k)) h += fmt("layout(location = %u) in vec4 in_attr%u;\n", k, k);
    for (u32 t = 0; t < 4; ++t) {
        bool used = false;
        for (const auto& i : p.insns) used |= i.vec_op() == vp::VEC_TXL && i.tex_num() == t;
        if (used) h += fmt("layout(set = 0, binding = %u) uniform sampler2D vtex%u;\n", kVertexTextureBinding + t, t);
    }
    static const char* const kVaryings[kVaryingCount] = {"col0", "col1", "bfc0", "bfc1", "fog", "tex0", "tex1", "tex2",
                                                         "tex3", "tex4", "tex5", "tex6", "tex7", "tex8", "tex9"};
    for (u32 k = 0; k < 13; ++k) h += fmt("layout(location = %u) out vec4 out_%s;\n", k, kVaryings[k]);
    h += kVertexHelpers;
    h += "void main() {\n";

    Out o;
    for (u32 k = 0; k < 48; ++k)
        if (p.temps_used & (1ull << k)) o.line(fmt("vec4 r%u = vec4(0.0);", k));
    o.line("ivec4 a0 = ivec4(0), a1 = ivec4(0);");
    o.line("vec4 cc0 = vec4(0.0), cc1 = vec4(0.0);");
    for (u32 k = 0; k < 16; ++k) o.line(fmt("vec4 o%u = vec4(0.0, 0.0, 0.0, 1.0);", k));

    const bool flow = !p.branch_targets.empty();
    if (flow) {
        o.line(fmt("int pc_ = %u, sp_ = 0;", p.start));
        o.line("int stack_[8];");
        o.line("while (true) {");
        ++o.indent;
        o.line("switch (pc_) {");
    }
    for (std::size_t k = 0; k < p.insns.size(); ++k) {
        const vp::Insn& i = p.insns[k];
        const u32 slot = p.start + static_cast<u32>(k);
        if (flow) o.line(fmt("case %u:", slot));
        o.line("{  // " + vp::disasm(i));
        ++o.indent;
        const std::string cond = vp_cond(i);
        const bool skip = cond == "false";
        if (!skip) {
            if (!cond.empty()) o.line("bvec4 c = " + cond + ";");
            const bool vec = i.vec_op() != vp::VEC_NOP;
            const bool sca = i.sca_op() != vp::SCA_NOP && !i.is_flow();
            // Dual issue: both ops read their sources before either writes.
            if (vec) o.line("vec4 tv = " + std::string(i.saturate() ? "clamp(" : "(") + vp_vec_value(i) +
                            (i.saturate() ? ", 0.0, 1.0);" : ");"));
            if (sca) o.line("vec4 ts = " + std::string(i.saturate() ? "clamp(" : "(") + vp_sca_value(i) +
                            (i.saturate() ? ", 0.0, 1.0);" : ");"));
            if (vec) vp_writes(o, i, false, "tv", cond);
            if (sca) vp_writes(o, i, true, "ts", cond);
            if (flow && i.is_flow()) {
                const std::string take = cond.empty() ? "true" : "any(c)";
                const u32 t = i.branch_target();
                switch (i.sca_op()) {
                case vp::SCA_BRA: case vp::SCA_BRI:
                    o.line(fmt("if (%s) { pc_ = %u; continue; }", take.c_str(), t));
                    break;
                case vp::SCA_BRB:
                    o.line(fmt("if (((pc.branch_bits >> %u) & 1u) %s 0u) { pc_ = %u; continue; }", i.branch_index(),
                               i.brb_cond_true() ? "!=" : "==", t));
                    break;
                case vp::SCA_CAL: case vp::SCA_CLI:
                    o.line(fmt("if (%s && sp_ < 8) { stack_[sp_++] = %u; pc_ = %u; continue; }", take.c_str(),
                               slot + 1, t));
                    break;
                case vp::SCA_CLB:
                    o.line(fmt("if ((((pc.branch_bits >> %u) & 1u) %s 0u) && sp_ < 8) { stack_[sp_++] = %u; pc_ = %u; continue; }",
                               i.branch_index(), i.brb_cond_true() ? "!=" : "==", slot + 1, t));
                    break;
                case vp::SCA_RET:
                    o.line(fmt("if (%s) { if (sp_ == 0) { pc_ = -1; break; } pc_ = stack_[--sp_]; continue; }",
                               take.c_str()));
                    break;
                default: break;
                }
            }
        }
        if (i.end()) o.line(flow ? "pc_ = -1; break;" : "");
        --o.indent;
        o.line("}");
        if (i.end() && !flow) break;
    }
    if (flow) {
        o.line("}");
        o.line("break;");
        --o.indent;
        o.line("}");
    }
    o.line("gl_Position = pc.scale_offset * o0;");
    for (u32 k = 0; k < 5; ++k) o.line(fmt("out_%s = o%u;", kVaryings[k], k + 1));
    for (u32 k = 0; k < 8; ++k) o.line(fmt("out_tex%u = o%u;", k, k + 7));
    if (p.outputs_written & (1u << 6)) o.line("gl_PointSize = o6.x;");
    return h + o.s + "}\n";
}

