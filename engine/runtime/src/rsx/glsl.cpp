std::string vp_src(const vp::Insn& i, int n) {
    const vp::Source s = i.src(n);
    std::string r;
    switch (s.type) {
    case vp::REG_TEMP: r = "r" + std::to_string(s.index); break;
    case vp::REG_INPUT: r = "in_attr" + std::to_string(s.index); break;
    case vp::REG_CONST:
        if (i.index_const()) {
            r = fmt("vc[clamp(a%u.%c + %u, 0, 467)]", i.addr_reg_sel(), kComp[i.addr_swz()], s.index);
        } else if (s.index < 468) {
            r = "vc[" + std::to_string(s.index) + "]";
        } else {
            r = "vec4(0.0)";
        }
        break;
    default: r = "vec4(0.0)"; break;
    }
    r += swizzle(s.swizzle);
    if (s.abs) r = "abs(" + r + ")";
    if (s.neg) r = "-" + r;
    return r;
}

std::string vp_vec_value(const vp::Insn& i) {
    const std::string a = vp_src(i, 0), b = vp_src(i, 1), c = vp_src(i, 2);
    switch (i.vec_op()) {
    case vp::VEC_MOV: return a;
    case vp::VEC_MUL: return "(" + a + " * " + b + ")";
    case vp::VEC_ADD: return "(" + a + " + " + c + ")";
    case vp::VEC_MAD: return "(" + a + " * " + b + " + " + c + ")";
    case vp::VEC_DP3: return "vec4(dot((" + a + ").xyz, (" + b + ").xyz))";
    case vp::VEC_DPH: return "vec4(dot((" + a + ").xyz, (" + b + ").xyz) + (" + b + ").w)";
    case vp::VEC_DP4: return "vec4(dot(" + a + ", " + b + "))";
    case vp::VEC_DST: return "vec4(1.0, (" + a + ").y * (" + b + ").y, (" + a + ").z, (" + b + ").w)";
    case vp::VEC_MIN: return "min(" + a + ", " + b + ")";
    case vp::VEC_MAX: return "max(" + a + ", " + b + ")";
    case vp::VEC_SLT: return "vec4(lessThan(" + a + ", " + b + "))";
    case vp::VEC_SGE: return "vec4(greaterThanEqual(" + a + ", " + b + "))";
    case vp::VEC_SLE: return "vec4(lessThanEqual(" + a + ", " + b + "))";
    case vp::VEC_SGT: return "vec4(greaterThan(" + a + ", " + b + "))";
    case vp::VEC_SNE: return "vec4(notEqual(" + a + ", " + b + "))";
    case vp::VEC_SEQ: return "vec4(equal(" + a + ", " + b + "))";
    case vp::VEC_SFL: return "vec4(0.0)";
    case vp::VEC_STR: return "vec4(1.0)";
    case vp::VEC_SSG: return "sign(" + a + ")";
    case vp::VEC_ARL: return a;
    case vp::VEC_FRC: return "fract(" + a + ")";
    case vp::VEC_FLR: return "floor(" + a + ")";
    case vp::VEC_TXL: return "textureLod(vtex" + std::to_string(i.tex_num()) + ", (" + a + ").xy, 0.0)";
    default: return "vec4(0.0)";
    }
}

std::string vp_sca_value(const vp::Insn& i) {
    const std::string s = vp_src(i, 2);
    switch (i.sca_op()) {
    case vp::SCA_MOV: return s;
    case vp::SCA_RCP: return "(1.0 / " + s + ")";
    case vp::SCA_RCC: return "clamp(1.0 / " + s + ", 5.42101e-20, 1.884467e19)";
    case vp::SCA_RSQ: return "vec4(inversesqrt(max(abs((" + s + ").x), 1.0e-38)))";
    case vp::SCA_EXP: return "_exp(" + s + ")";
    case vp::SCA_LOG: return "_log(" + s + ")";
    case vp::SCA_LIT: return "_lit(" + s + ")";
    case vp::SCA_LG2: return "vec4(log2(max(abs((" + s + ").x), 1.0e-38)))";
    case vp::SCA_EX2: return "exp2(" + s + ")";
    case vp::SCA_SIN: return "sin(" + s + ")";
    case vp::SCA_COS: return "cos(" + s + ")";
    default: return "vec4(0.0)";  // PSH/POP: address stack, unused by known content
    }
}

std::string vp_cond(const vp::Insn& i) {
    if (!i.cond_test()) return "";
    const u8 sw[4] = {static_cast<u8>(i.mask_x()), static_cast<u8>(i.mask_y()), static_cast<u8>(i.mask_z()),
                      static_cast<u8>(i.mask_w())};
    return cond_expr(i.cond(), "cc" + std::to_string(i.cond_reg_sel()) + swizzle(sw));
}

void vp_writes(Out& o, const vp::Insn& i, bool sca, const std::string& value, const std::string& cond) {
    const std::string m = mask_vp(sca ? i.sca_mask() : i.vec_mask());
    const u32 tmp = sca ? i.sca_dst_tmp() : i.dst_tmp();
    const bool result = sca ? !i.vec_result() : i.vec_result();
    bool wrote = false;
    if (result && i.dst() != 0x1F && i.dst() < 16) {
        write_masked(o, "o" + std::to_string(i.dst()), m, value, cond);
        wrote = true;
    }
    if (tmp != 0x3F) {
        const bool arl = !sca && i.vec_op() == vp::VEC_ARL;
        write_masked(o, (arl ? "a" : "r") + std::to_string(arl ? tmp & 1 : tmp), m, value, cond, arl);
        wrote = true;
    }
    if (i.cond_update0() || i.cond_update1() || !wrote)
        write_masked(o, "cc" + std::to_string(i.cond_reg_sel()), m, value, cond);
}

